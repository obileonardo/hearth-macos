#!/usr/bin/env python3
"""WCAG 2.2 contrast for Hearth's colour tokens, in the dark and light appearances.

Mirrors Theme.swift and Appearance.swift (Color.accent's deepening included), so the table in
docs/accessibility.md can be regenerated after a token changes:

    python3 scripts/contrast.py > /tmp/table.md
"""
import colorsys
import sys
import re
from pathlib import Path


def lin(v):
    return v / 12.92 if v <= 0.03928 else ((v + 0.055) / 1.055) ** 2.4


def lum(c):
    r, g, b = c
    return 0.2126 * lin(r) + 0.7152 * lin(g) + 0.0722 * lin(b)


def ratio(a, b):
    la, lb = lum(a), lum(b)
    return (max(la, lb) + 0.05) / (min(la, lb) + 0.05)


def over(fg, alpha, bg):
    return tuple(f * alpha + b * (1 - alpha) for f, b in zip(fg, bg))


WHITE, BLACK = (1, 1, 1), (0, 0, 0)
DARK_BASE = (0.027, 0.027, 0.034)
LIGHT_BASE = (0.957, 0.957, 0.965)
# A card in the dark: the tray's white 2.5% plus the core's white 7% over the base.
DARK_CARD = over(WHITE, 0.07, over(WHITE, 0.025, DARK_BASE))
LIGHT_CARD = WHITE


def deepened(c, target):
    h, s, v = colorsys.rgb_to_hsv(*c)
    sat = s if s < 0.08 else min(1, s * 1.15 + 0.3)
    while True:
        out = colorsys.hsv_to_rgb(h, sat, v)
        v -= 0.01
        if ratio(out, LIGHT_BASE) >= target or v <= 0.05:
            return out


# (name, dark colour or (colour, alpha), light colour or (colour, alpha), use)
INK = (0.07, 0.07, 0.09)
BRAND_DARK, BRAND_LIGHT = (0.26, 0.61, 0.99), (0.07, 0.30, 0.65)
BRAND_END_DARK, BRAND_END_LIGHT = (0.22, 0.55, 0.94), (0.06, 0.24, 0.54)
HOME_DARK, HOME_LIGHT = (0.27, 0.82, 0.56), (0.04, 0.42, 0.25)
HOME_END_DARK, HOME_END_LIGHT = (0.21, 0.72, 0.46), (0.03, 0.33, 0.19)
tokens = [
    ("ink", (WHITE, 0.95), INK, "Titles, values, body"),
    ("muted", (WHITE, 0.68), (0.33, 0.33, 0.36), "Secondary text"),
    ("faint", (WHITE, 0.5), (0.42, 0.42, 0.45), "Section labels, captions"),
    ("brand / sand", BRAND_DARK, BRAND_LIGHT, "Blue accent text, links"),
    ("brandEnd", BRAND_END_DARK, BRAND_END_LIGHT, "Blue gradient endpoint"),
    ("homeEnergy", HOME_DARK, HOME_LIGHT, "Home consumption"),
    ("homeEnergyEnd", HOME_END_DARK, HOME_END_LIGHT, "Home gradient endpoint"),
    ("ok", (0.5, 0.9, 0.62), (0.09, 0.47, 0.24), "Online, armed"),
    ("live", (1.0, 0.36, 0.32), (0.78, 0.13, 0.11), "Alerts, live"),
    ("air cool", (0.7, 0.85, 1.0), (0.07, 0.4, 0.78), "AC mode colour"),
    ("air heat", (1.0, 0.74, 0.5), (0.68, 0.31, 0.02), "AC mode colour"),
    ("air dry", (0.62, 0.94, 0.88), (0.0, 0.47, 0.42), "AC mode colour"),
    ("air fan", (0.9, 0.92, 0.96), (0.33, 0.37, 0.45), "AC mode colour"),
    ("air auto", (0.8, 0.78, 1.0), (0.38, 0.3, 0.78), "AC mode colour"),
]
for name, c in [("accent: doorbell blue", (0.45, 0.75, 1.0)),
                ("accent: solar", (1.0, 0.78, 0.38)), ("accent: battery", (0.5, 0.92, 0.64)),
                ("accent: grid", (0.7, 0.72, 1.0)), ("accent: car", (0.42, 0.92, 0.7))]:
    tokens.append((name, c, deepened(c, 4.6), "Generated by Color.accent"))


def resolve(spec, bg):
    if isinstance(spec[0], tuple):
        colour, alpha = spec
        return over(colour, alpha, bg)
    return spec


print("| Token | Use | Dark on panel | Dark on card | Light on panel | Light on card |")
print("|---|---|---|---|---|---|")
worst = 99
for name, dark, light, use in tokens:
    cells = []
    for spec, bgs in ((dark, (DARK_BASE, DARK_CARD)), (light, (LIGHT_BASE, LIGHT_CARD))):
        for bg in bgs:
            r = ratio(resolve(spec, bg), bg)
            worst = min(worst, r)
            cells.append(f"{r:.1f}:1")
    print(f"| {name} | {use} | " + " | ".join(cells) + " |")

print()
print("| Pairing | Dark | Light |")
print("|---|---|---|")
pairs = [
    ("Main button text (onCTA on cta)", (BLACK, WHITE), (WHITE, (0.09, 0.09, 0.11))),
    ("Text on blue (onAccent)", (over(BLACK, 0.88, BRAND_DARK), BRAND_DARK), (WHITE, BRAND_LIGHT)),
    ("Text on blue endpoint", (over(BLACK, 0.88, BRAND_END_DARK), BRAND_END_DARK), (WHITE, BRAND_END_LIGHT)),
    ("Text on home green", (over(BLACK, 0.88, HOME_DARK), HOME_DARK), (WHITE, HOME_LIGHT)),
    ("Text on home green endpoint", (over(BLACK, 0.88, HOME_END_DARK), HOME_END_DARK), (WHITE, HOME_END_LIGHT)),
    ("Selected segment text on its white key", (over(BLACK, 0.86, WHITE), WHITE), (INK, WHITE)),
    ("Text on a live photo scrim (white on 45% black over mid-grey)", (WHITE, over(BLACK, 0.45, (0.5, 0.5, 0.5))),
     (WHITE, over(BLACK, 0.45, (0.5, 0.5, 0.5)))),
]
for name, d, l in pairs:
    worst = min(worst, ratio(*d), ratio(*l))
    print(f"| {name} | {ratio(*d):.1f}:1 | {ratio(*l):.1f}:1 |")

print()
print("| Non-text part (needs 3:1) | Dark | Light |")
print("|---|---|---|")
for name, d, l in [
    ("Hairline, Increase Contrast on", (over(WHITE, 0.42, DARK_BASE), DARK_BASE), (over(BLACK, 0.48, LIGHT_BASE), LIGHT_BASE)),
    ("Text field outline while typing", (over(WHITE, 0.95 * 0.6, over(BLACK, 0.32, DARK_CARD)), DARK_CARD),
     (over(INK, 0.6, WHITE), WHITE)),
]:
    print(f"| {name} | {ratio(*d):.1f}:1 | {ratio(*l):.1f}:1 |")

# Blue/green appear as text and as gradient fills. Check intermediate stops as
# well as endpoints, including their Increase Contrast overrides. Decorative
# hairlines are deliberately excluded from the text threshold.
gradients = [
    (BRAND_DARK, BRAND_END_DARK, BRAND_LIGHT, BRAND_END_LIGHT),
    (HOME_DARK, HOME_END_DARK, HOME_LIGHT, HOME_END_LIGHT),
    ((0.48, 0.75, 1.0), (0.42, 0.70, 0.99), (0.04, 0.24, 0.53), (0.03, 0.18, 0.44)),
    ((0.46, 0.92, 0.69), (0.38, 0.84, 0.60), (0.02, 0.32, 0.18), (0.01, 0.25, 0.13)),
]
for dark_start, dark_end, light_start, light_end in gradients:
    for step in range(21):
        t = step / 20
        dark = over(dark_end, t, dark_start)
        light = over(light_end, t, light_start)
        worst = min(worst, ratio(dark, DARK_BASE), ratio(dark, DARK_CARD),
                    ratio(light, LIGHT_BASE), ratio(light, LIGHT_CARD),
                    ratio(over(BLACK, 0.88, dark), dark), ratio(WHITE, light))
if worst < 4.5:
    print(f"FAIL: minimum text contrast {worst:.3f}:1 is below 4.5:1", file=sys.stderr)
    raise SystemExit(1)
if "--verify-source" in sys.argv:
    # Fail if the mirrored palette drifts from the actual Swift definitions.
    source = (Path(__file__).resolve().parent.parent / "Sources/Hearth/Views/Theme.swift").read_text()
    expected = {
        "brand": (BRAND_DARK, BRAND_LIGHT, gradients[2][0], gradients[2][2]),
        "brandEnd": (BRAND_END_DARK, BRAND_END_LIGHT, gradients[2][1], gradients[2][3]),
        "homeEnergy": (HOME_DARK, HOME_LIGHT, gradients[3][0], gradients[3][2]),
        "homeEnergyEnd": (HOME_END_DARK, HOME_END_LIGHT, gradients[3][1], gradients[3][3]),
    }
    for name, values in expected.items():
        block = source.split(f"static let {name} = Color.adaptive(", 1)[1].split("\n    static", 1)[0]
        for key, value in zip(("dark", "light", "darkHC", "lightHC"), values):
            match = re.search(rf"\b{key}:\s*\.rgb\(([^)]+)\)", block)
            actual = tuple(float(component.strip()) for component in match[1].split(",")) if match else ()
            if actual != value:
                raise SystemExit(f"FAIL: Theme.{name} {key} differs from mirrored contrast value")
    print("PASS: blue/green normal and Increase Contrast values match Theme.swift", file=sys.stderr)
print(f"PASS: minimum calculated text contrast {worst:.3f}:1", file=sys.stderr)
